#!/usr/bin/env python3
"""Regenerate src/videos/registry.ts from every src/videos/<slug>/ that has scene.js + timing.json."""
import os, re

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'videos')


def comp_id(slug):
    return 'Geister' if slug == 'geister' else re.sub(r'[^A-Za-z0-9-]', '-', slug)


def main():
    slugs = sorted(d for d in os.listdir(ROOT)
                   if os.path.isfile(os.path.join(ROOT, d, 'scene.js')) and os.path.isfile(os.path.join(ROOT, d, 'timing.json')))
    lines = ['// AUTO-GENERATED by scripts/gen_registry.py — do not edit by hand.', '// @ts-nocheck']
    for i, s in enumerate(slugs):
        lines.append(f"import * as m{i} from './{s}/scene.js';")
        lines.append(f"import t{i} from './{s}/timing.json';")
    lines.append('export const REGISTRY: Record<string, { id: string; mod: any; timing: any }> = {')
    for i, s in enumerate(slugs):
        lines.append(f"  '{s}': {{ id: '{comp_id(s)}', mod: m{i}, timing: t{i} }},")
    lines.append('};')
    open(os.path.join(ROOT, 'registry.ts'), 'w').write('\n'.join(lines) + '\n')
    print('registry:', ', '.join(f'{s}->{comp_id(s)}' for s in slugs))


if __name__ == '__main__':
    main()
