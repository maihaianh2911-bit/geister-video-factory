#!/usr/bin/env python3
"""Build a deterministic scene router for storyboard shots with local scene_module files.
Each module exports default renderShot(t); shared helpers are local static JS imports.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def source(video, board):
    imports, spans = [], []
    for i, shot in enumerate(board):
        name = shot.get('scene_module')
        if not isinstance(name, str) or not name.startswith('shots/') or not name.endswith('.js') or '..' in Path(name).parts:
            raise ValueError(f'Cảnh {i + 1}: scene_module phải là shots/<tên>.js')
        imports.append(f'import shot{i} from {json.dumps("./" + name)};')
        spans.append([shot['t0'], shot['t1']])
    style_path = video / 'style.json'
    style = json.loads(style_path.read_text()) if style_path.exists() else {}
    if not isinstance(style, dict): raise ValueError('style.json must be an object')
    return ('// AUTO-GENERATED by scripts/scene_modules.py; edit the shot modules, then rebuild.\n'
            "import { DEFS, dust } from '../../engine/core.js';\n" + '\n'.join(imports) + '\n'
            + 'const SPANS = ' + json.dumps(spans) + ';\n'
            + 'const SHOTS = [' + ', '.join(f'shot{i}' for i in range(len(board))) + '];\n'
            + 'const STYLE = ' + json.dumps(style) + ';\n'
            + "export const subtitleStyle = STYLE.subtitle || 'default';\n"
            + 'export const subtitleTop = STYLE.subtitle_y;\nexport const subtitleChars = STYLE.subtitle_chars;\nexport const subtitleSize = STYLE.subtitle_size;\n'
            + 'export function __scene(t) {\n  let i = SPANS.findIndex(([a,b]) => a <= t && t < b);\n  if (i < 0) i = t < SPANS[0][0] ? 0 : SPANS.length - 1;\n  return SHOTS[i](t);\n}\n'
            + 'export function renderSvg(t) { return DEFS + __scene(t) + (STYLE.dust === false ? "" : dust(t)) + (STYLE.vignette === false ? "" : `<rect width="1080" height="1920" fill="url(#gVig)"/>`); }\n'
            + "export function subtitleAt() { return ''; }\n")


def dependencies(root, video, board):
    expected = source(video, board)
    if (video / 'scene.js').read_text() != expected:
        raise ValueError('Router cảnh đã thay đổi; chạy python3 scripts/scene_modules.py <mã> trước khi duyệt')
    entries = [str((video / s['scene_module']).relative_to(root)) for s in board]
    try:
        result = subprocess.run(['node', str(root / 'scripts/module_dependencies.cjs'), str(root), json.dumps(entries)],
                                text=True, capture_output=True, check=True)
    except subprocess.CalledProcessError as e:
        raise ValueError('Không xác định được phụ thuộc cảnh: ' + e.stderr.strip()) from e
    return json.loads(result.stdout)


if __name__ == '__main__':
    if len(sys.argv) != 2 or not sys.argv[1].replace('-', '').replace('_', '').isalnum():
        raise SystemExit('Usage: python3 scripts/scene_modules.py <slug>')
    video = ROOT / 'src/videos' / sys.argv[1]
    board = json.loads((video / 'storyboard.json').read_text())
    (video / 'scene.js').write_text(source(video, board), encoding='utf-8')
    dependencies(ROOT, video, board)
    print('Built modular scene router:', sys.argv[1])
